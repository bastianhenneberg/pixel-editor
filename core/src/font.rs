fn glyph(c: char) -> &'static [&'static str; 5] {
    GLYPHS
        .iter()
        .find(|(g, _)| *g == c)
        .or_else(|| GLYPHS.iter().find(|(g, _)| *g == c.to_ascii_uppercase()))
        .or_else(|| GLYPHS.iter().find(|(g, _)| *g == '?'))
        .map(|(_, rows)| rows)
        .unwrap()
}

/// Cut `text` so it fits into `max_w` pixels, marking the cut with `~`.
pub fn fit_text(text: &str, scale: u32, max_w: u32) -> String {
    if text_width(text, scale) <= max_w {
        return text.to_string();
    }
    let mut t: String = text.to_string();
    while !t.is_empty() && text_width(&format!("{t}~"), scale) > max_w {
        t.pop();
    }
    format!("{t}~")
}

/// Width in pixels of `text` at `scale` (1 px spacing between glyphs).
pub fn text_width(text: &str, scale: u32) -> u32 {
    let n = text.chars().count() as u32;
    if n == 0 {
        0
    } else {
        (n * (GLYPH_W + 1) - 1) * scale
    }
}

pub fn text_height(scale: u32) -> u32 {
    GLYPH_H * scale
}

/// Draw text with its top-left corner at (x, y).
pub fn draw_text(img: &mut Image, x: i32, y: i32, text: &str, scale: u32, color: [u8; 4]) {
    let s = scale.max(1) as i32;
    for (i, c) in text.chars().enumerate() {
        let gx = x + i as i32 * (GLYPH_W as i32 + 1) * s;
        for (row, bits) in glyph(c).iter().enumerate() {
            for (col, b) in bits.bytes().enumerate() {
                if b == b'#' {
                    for dy in 0..s {
                        for dx in 0..s {
                            let (px, py) = (gx + col as i32 * s + dx, y + row as i32 * s + dy);
                            if px >= 0 && py >= 0 {
                                img.put(px as u32, py as u32, color);
                            }
                        }
                    }
                }
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glyphs_well_formed() {
        for (c, rows) in GLYPHS {
            for r in rows {
                assert_eq!(r.len(), GLYPH_W as usize, "glyph {c:?}");
                assert!(r.bytes().all(|b| b == b'#' || b == b'.'));
            }
        }
        let mut seen: Vec<char> = GLYPHS.iter().map(|(c, _)| *c).collect();
        seen.sort();
        seen.dedup();
        assert_eq!(seen.len(), GLYPHS.len(), "duplicate glyph");
    }

    #[test]
    fn draws_exact_pixels() {
        let mut img = Image::new(8, 10);
        draw_text(&mut img, 0, 0, "1", 2, [255, 0, 0, 255]);
        assert_eq!(img.get(2, 0), [255, 0, 0, 255]); // top of the "1" stem, scaled 2x
        assert_eq!(img.get(0, 0), [0, 0, 0, 0]);
        assert_eq!(text_width("10", 2), 14);
    }
}
